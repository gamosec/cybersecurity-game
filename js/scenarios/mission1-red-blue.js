  function workstation(I, x, y, color, screenFill, label, station) {
    const P = (a, b, c) => I.p(a, b, c);
    const dark = CE.shade(color, -0.2);
    let g = '<g data-station="' + station + '" data-hit="self">';
    // منطقة نقر تغطي المكتب كاملًا
    const c0 = P(x - 6, y - 6, 0), c1 = P(x + 70, y + 60, 118);
    g += '<rect class="hit" x="' + Math.min(c0[0], c1[0] - 10) + '" y="' + (c1[1] - 10) + '" width="150" height="150" rx="14"/>';
    // المكتب
    g += I.box(x, y, 0, 64, 52, 6, '#c9b79a', { top: '#dcc8a6', left: '#b7a07a', right: '#a9956f' });
    g += I.box(x + 4, y + 4, 0, 6, 6, 60, '#3a434e') + I.box(x + 54, y + 4, 0, 6, 6, 60, '#3a434e');
    g += I.box(x + 4, y + 42, 0, 6, 6, 60, '#3a434e') + I.box(x + 54, y + 42, 0, 6, 6, 60, '#3a434e');
    // صندوق أدراج ملون (يميّز المحطة)
    g += I.box(x + 22, y + 44, 0, 30, 24, 54, color, { top: CE.shade(color, 0.12), left: color, right: dark });
    g += I.poly([[x + 22, y + 68.4, 36], [x + 52, y + 68.4, 36], [x + 52, y + 68.4, 38], [x + 22, y + 68.4, 38]], dark);
    // الشاشة
    g += I.box(x + 20, y + 10, 66, 34, 6, 3, '#2f3b48');
    g += I.box(x + 34, y + 14, 69, 6, 6, 20, '#2f3b48');
    g += '<g transform="' + I.onPlaneY(x + 16, y + 16.3, 128) + '">' +
      '<rect width="44" height="30" rx="1.5" fill="' + screenFill + '"/>' +
      '<circle cx="22" cy="11" r="6" fill="#fff" opacity=".9"/>' +
      '<path d="M12 25q10-9 20 0Z" fill="#fff" opacity=".9"/>' +
      '<text x="22" y="28.5" font-size="5" font-weight="700" fill="#fff" text-anchor="middle">' + label + '</text>' +
      '</g>';
    // كرسي بلون الفريق
    g += I.box(x + 8, y + 70, 0, 40, 6, 4, dark) + I.box(x + 26, y + 54, 0, 6, 40, 4, dark);
    g += I.box(x + 25, y + 73, 4, 8, 8, 40, dark);
    g += I.box(x + 2, y + 50, 42, 52, 48, 8, color, { top: CE.shade(color, 0.1) });
    g += I.box(x + 4, y + 96, 50, 48, 7, 54, CE.shade(color, -0.08));
    g += '</g>';
    return g;
  }

